static uint32_t crc32_gf2_matrix_times(const uint32_t* matrix,
                                       uint32_t vector)
{
    uint32_t result = 0;

    while (vector != 0) {
        if (vector & 1u)
            result ^= *matrix;
        vector >>= 1;
        ++matrix;
    }

    return result;
}

static void crc32_gf2_matrix_square(uint32_t* square,
                                    const uint32_t* matrix)
{
    for (unsigned index = 0; index < XCrc32_GF2_DIM; ++index)
        square[index] = crc32_gf2_matrix_times(matrix, matrix[index]);
}

static uint32_t crc32_shift_zero_bytes(uint32_t value, uint64_t length,
                                       uint32_t polynomial, int reflected)
{
    uint32_t even[XCrc32_GF2_DIM];
    uint32_t odd[XCrc32_GF2_DIM];

    if (length == 0)
        return value;

    if (reflected) {
        odd[0] = polynomial;
        for (unsigned index = 1; index < XCrc32_GF2_DIM; ++index)
            odd[index] = 1u << (index - 1);
    } else {
        for (unsigned index = 0; index < XCrc32_GF2_DIM - 1; ++index)
            odd[index] = 1u << (index + 1);
        odd[XCrc32_GF2_DIM - 1] = polynomial;
    }

    crc32_gf2_matrix_square(even, odd);
    crc32_gf2_matrix_square(odd, even);

    do {
        crc32_gf2_matrix_square(even, odd);
        if (length & 1u)
            value = crc32_gf2_matrix_times(even, value);
        length >>= 1;

        if (length == 0)
            break;

        crc32_gf2_matrix_square(odd, even);
        if (length & 1u)
            value = crc32_gf2_matrix_times(odd, value);
        length >>= 1;
    } while (length != 0);

    return value;
}

static uint32_t crc32_combine_parameters(uint32_t crc1, uint32_t crc2,
                                         uint64_t length2, uint32_t initial,
                                         uint32_t xorout, uint32_t polynomial,
                                         int reflected)
{
    if (length2 == 0)
        return crc1;

    return crc32_shift_zero_bytes(crc1 ^ initial ^ xorout, length2,
                                   polynomial, reflected) ^ crc2;
}

