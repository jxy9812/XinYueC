#define XCrc32_UPDATE_WORD(state, data)                                      \
    do {                                                                      \
        uint32_t word = (uint32_t)(data)[0] |                                \
                        ((uint32_t)(data)[1] << 8) |                          \
                        ((uint32_t)(data)[2] << 16) |                         \
                        ((uint32_t)(data)[3] << 24);                          \
        (state) ^= word;                                                      \
        (state) = crc32_table[3][(state) & 0xFFu] ^                          \
                  crc32_table[2][((state) >> 8) & 0xFFu] ^                    \
                  crc32_table[1][((state) >> 16) & 0xFFu] ^                   \
                  crc32_table[0][(state) >> 24];                              \
        (data) += 4;                                                          \
    } while (0)

static uint32_t crc32_update_raw(uint32_t state, const uint8_t* data,
                                 size_t length)
{
    while (length >= 32) {
        XCrc32_UPDATE_WORD(state, data);
        XCrc32_UPDATE_WORD(state, data);
        XCrc32_UPDATE_WORD(state, data);
        XCrc32_UPDATE_WORD(state, data);
        XCrc32_UPDATE_WORD(state, data);
        XCrc32_UPDATE_WORD(state, data);
        XCrc32_UPDATE_WORD(state, data);
        XCrc32_UPDATE_WORD(state, data);
        length -= 32;
    }

    while (length >= 4) {
        XCrc32_UPDATE_WORD(state, data);
        length -= 4;
    }

    while (length-- != 0)
        state = (state >> 8) ^ crc32_table[0][(state ^ *data++) & 0xFFu];

    return state;
}

