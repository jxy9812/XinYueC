uint32_t XCrc32_update(XCrc32_Algorithm algorithm, uint32_t crc,
                       const uint8_t* data, size_t length)
{
    if (data == NULL && length != 0)
        return 0;

    switch (algorithm) {
#if XCrc32_IsoHdlc_ON
    case XCrc32_Algorithm_IsoHdlc:
        return crc32_update_raw(crc ^ 0xFFFFFFFFu, data, length) ^
               0xFFFFFFFFu;
#endif
#if XCrc32_Castagnoli_ON
    case XCrc32_Algorithm_Castagnoli:
        return crc32_update_reflected_table(crc32_castagnoli_table, crc,
                                            0xFFFFFFFFu, data, length);
#endif
#if XCrc32_Mpeg2_ON
    case XCrc32_Algorithm_Mpeg2:
        return crc32_update_normal_table(crc32_ieee_normal_table, crc,
                                         0x00000000u, data, length);
#endif
#if XCrc32_Bzip2_ON
    case XCrc32_Algorithm_Bzip2:
        return crc32_update_normal_table(crc32_ieee_normal_table, crc,
                                         0xFFFFFFFFu, data, length);
#endif
#if XCrc32_Posix_ON
    case XCrc32_Algorithm_Posix:
        return crc32_update_normal_table(crc32_ieee_normal_table, crc,
                                         0xFFFFFFFFu, data, length);
#endif
#if XCrc32_Jamcrc_ON
    case XCrc32_Algorithm_Jamcrc:
        return crc32_update_raw(crc, data, length);
#endif
#if XCrc32_Q_ON
    case XCrc32_Algorithm_Q:
        return crc32_update_normal_table(crc32_q_table, crc,
                                         0x00000000u, data, length);
#endif
#if XCrc32_Xfer_ON
    case XCrc32_Algorithm_Xfer:
        return crc32_update_normal_table(crc32_xfer_table, crc,
                                         0x00000000u, data, length);
#endif
    default:
        return 0;
    }
}

uint32_t XCrc32_calculate(XCrc32_Algorithm algorithm,
                          const uint8_t* data, size_t length)
{
    return XCrc32_update(algorithm, XCrc32_initialize(algorithm), data,
                         length);
}

