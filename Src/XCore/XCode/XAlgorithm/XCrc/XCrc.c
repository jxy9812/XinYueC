static uint32_t crc32_update_reflected_table(
    const uint32_t table[256], uint32_t crc, uint32_t xorout,
    const uint8_t* data, size_t length)
{
    uint32_t state = crc ^ xorout;

    while (length-- != 0)
        state = (state >> 8) ^ table[(state ^ *data++) & 0xFFu];

    return state ^ xorout;
}

static uint32_t crc32_update_normal_table(
    const uint32_t table[256], uint32_t crc, uint32_t xorout,
    const uint8_t* data, size_t length)
{
    uint32_t state = crc ^ xorout;

    while (length-- != 0)
        state = (state << 8) ^
                table[((state >> 24) ^ *data++) & 0xFFu];

    return state ^ xorout;
}

