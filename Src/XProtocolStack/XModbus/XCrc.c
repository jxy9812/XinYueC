/**
 * @brief 计算 Modbus RTU 协议的 CRC-16 校验值
 * 
 * Modbus RTU 使用 CRC-16 校验确保数据完整性，初始值为 0xFFFF（高低位均为 0xFF），
 * 逐字节处理数据帧，最终结果以小端模式（低位在前，高位在后）附加到帧尾。
 * 
 * @param pucFrame 指向待计算数据帧的指针（包含从机地址、功能码、数据域，不包含 CRC 自身）
 * @param usLen    数据帧长度（字节数，范围 1~256，包含从机地址到数据域的所有字节）
 * 
 * @return         16 位 CRC 校验值（高位在前，低位在后，如返回 0x8005 表示实际校验值为 0x0580）
 * 
 * @note           1. 输入数据必须不包含已有的 CRC 字节
 *                 2. 结果需拆分为低高位字节，以小端模式添加到帧尾（低位先，高位后）
 */
uint16_t XCRC16(uint8_t *pucFrame, uint16_t usLen) {
    uint8_t           ucCRCHi = 0xFF;  // CRC 高位寄存器初始化（Modbus 规定初始值 0xFF）
    uint8_t           ucCRCLo = 0xFF;  // CRC 低位寄存器初始化（Modbus 规定初始值 0xFF）
    int             iIndex;         // 查找表索引，由当前 CRC 低位与输入字节异或得到

    // 遍历数据帧中的每个字节，更新 CRC 校验值
    while (usLen--) {
        // 计算索引：当前 CRC 低位与输入字节异或（得到 0x00~0xFF 的索引值）
        iIndex = ucCRCLo ^ *(pucFrame++);  // 处理当前字节后，指针指向下一个字节

        // 更新 CRC 高位：原高位 ^ 高位表中索引对应的值（实现多项式模运算）
        ucCRCHi = (uint8_t)(ucCRCHi ^ aucCRCHi[iIndex]);
        
        // 更新 CRC 低位：直接使用低位表中索引对应的值（预计算的快速更新值）
        ucCRCLo = aucCRCLo[iIndex];
    }

    // 组合高低位得到最终 CRC 值（高位左移 8 位 + 低位，形成 16 位无符号短整型）
    return (uint16_t)(ucCRCHi << 8 | ucCRCLo);
}