{
    return IME_SYLLABLE_COUNT;
}

uint16_t XPinyinTable_entryCount(void)
{
    return IME_ENTRY_COUNT;
}

uint16_t XPinyinTable_rankLimit(void)
{
#if (XKEYBOARD_IME_RANK_LIMIT > 0)
    return (uint16_t)XKEYBOARD_IME_RANK_LIMIT;
#else
    return 0;
#endif
}

const char* XPinyinTable_syllableAt(uint16_t syllableId)
{
    if (syllableId >= IME_SYLLABLE_COUNT)
    {
        return NULL;
    }
    return k_imeSyllables[syllableId];
}

bool XPinyinTable_isLegalSyllable(const char* syllable)
{
    uint16_t id;

    if (!syllable)
    {
        return false;
    }
    return imeFindSyllableId(syllable, &id);
}

bool XPinyinTable_syllableIdOf(const char* syllable, uint16_t* outId)
{
    if (!syllable)
    {
        return false;
    }
    return imeFindSyllableId(syllable, outId);
}

bool XPinyinTable_find(const char* syllable,
                            const XPinyinTableEntry** outBegin,
                            uint16_t* outCount)
{
    uint16_t id;
    uint16_t begin;
    uint16_t end;
    uint16_t count;
    uint16_t limit;
    uint16_t i;

    if (outBegin)
    {
        *outBegin = NULL;
    }
    if (outCount)
    {
        *outCount = 0;
    }
    if (!syllable || !outBegin || !outCount)
    {
        return false;
    }
    if (!imeFindSyllableId(syllable, &id))
    {
        return false;
    }
    begin = imeGroupBegin(id);
    end = begin;
    while ((end < IME_ENTRY_COUNT) && (k_imeEntries[end].m_syllable == id))
    {
        ++end;
    }
    count = (uint16_t)(end - begin);
    limit = XPinyinTable_rankLimit();
    if (limit > 0)
    {
        uint16_t trimmed = 0;

        for (i = begin; i < end; ++i)
        {
            if (k_imeEntries[i].m_rank > limit)
            {
                break;
            }
            ++trimmed;
        }
        count = trimmed;
    }
    if (count == 0)
    {
        return false;
    }
    *outBegin = &k_imeEntries[begin];
    *outCount = count;
    return true;
}

bool XPinyinTable_hasSyllablePrefix(const char* prefix)
{
    uint16_t lower;

    if (!prefix)
    {
        return false;
    }
    /* 音节表按字典序存放：以 prefix 开头的音节若存在，必 >= prefix，
       故首个 >= prefix 的音节（下界）若不以 prefix 开头，其后继在分歧
       字节上只会更大，更不可能以 prefix 开头——查下界一个即完备。 */
    lower = imeSyllableLowerBound(prefix);
    if (lower >= IME_SYLLABLE_COUNT)
    {
        return false;
    }
    return imeSyllableStartsWith(k_imeSyllables[lower], prefix);
}

