/**
 * @brief      内部音节串比较（白名单外不引入 string.h，逐字节字典序）。
 * @param      a 比较串借用指针；不为 NULL。
 * @param      b 比较串借用指针；不为 NULL。
 * @return     a<b 返回负数；相等返回 0；a>b 返回正数。
 */
static int imeSyllableCompare(const char* a, const char* b)
{
    while ((*a != '\0') && (*a == *b))
    {
        ++a;
        ++b;
    }
    return (int)(uint8_t)*a - (int)(uint8_t)*b;
}

/**
 * @brief      内部音节二分查找。
 * @param      syllable 音节串借用指针；不为 NULL。
 * @param      outId 调用方提供存储空间；命中时接收音节 id。
 * @return     命中返回 true；未命中返回 false（outId 不写）。
 */
/**
 * @brief      内部音节表下界二分（首个 >= prefix 的音节下标）。
 * @param      prefix 目标前缀串借用指针；不为 NULL。
 * @return     下界下标；越界时为 IME_SYLLABLE_COUNT。
 */
static uint16_t imeSyllableLowerBound(const char* prefix)
{
    uint16_t low = 0;
    uint16_t high = IME_SYLLABLE_COUNT;

    while (low < high)
    {
        uint16_t mid = (uint16_t)((low + high) / 2);

        if (imeSyllableCompare(k_imeSyllables[mid], prefix) < 0)
        {
            low = (uint16_t)(mid + 1);
        }
        else
        {
            high = mid;
        }
    }
    return low;
}

/**
 * @brief      内部音节串逐字节前缀匹配。
 * @param      syllable 音节串借用指针；不为 NULL。
 * @param      prefix 前缀串借用指针；不为 NULL。
 * @return     syllable 以 prefix 开头返回 true；否则 false。
 */
static bool imeSyllableStartsWith(const char* syllable, const char* prefix)
{
    while (*prefix != '\0')
    {
        if (*syllable != *prefix)
        {
            return false;
        }
        ++syllable;
        ++prefix;
    }
    return true;
}

static bool imeFindSyllableId(const char* syllable, uint16_t* outId)
{
    uint16_t low = 0;
    uint16_t high = IME_SYLLABLE_COUNT;

    while (low < high)
    {
        uint16_t mid = (uint16_t)((low + high) / 2);
        int cmp = imeSyllableCompare(syllable, k_imeSyllables[mid]);

        if (cmp == 0)
        {
            *outId = mid;
            return true;
        }
        if (cmp < 0)
        {
            high = mid;
        }
        else
        {
            low = (uint16_t)(mid + 1);
        }
    }
    return false;
}

/**
 * @brief      内部条目表下界二分（首个 m_syllable >= id 的下标）。
 * @param      id 目标音节 id；任意。
 * @return     下界下标；越界时为 IME_ENTRY_COUNT。
 */
static uint16_t imeGroupBegin(uint16_t id)
{
    uint16_t low = 0;
    uint16_t high = IME_ENTRY_COUNT;

    while (low < high)
    {
        uint16_t mid = (uint16_t)((low + high) / 2);

        if (k_imeEntries[mid].m_syllable < id)
        {
            low = (uint16_t)(mid + 1);
        }
        else
        {
            high = mid;
        }
    }
    return low;
}

