/* ==================== 字形数据读取（不实现任何算法） ==================== */

void XFont8x16_loadGlyph(uint32_t cp, unsigned char out[XFONT8X16_HEIGHT])
{
    int i;
    if (!out)
        return;
    if (cp < 128u)
    {
        for (i = 0; i < 8; ++i)
        {
            out[i * 2] = font8x8_basic[cp][i];
            out[i * 2 + 1] = font8x8_basic[cp][i];
        }
    }
    else
    {
        for (i = 0; i < XFONT8X16_HEIGHT; ++i)
            out[i] = font8x16_replacement[i];
    }
}
