/**
 * @brief 按文件名查找内嵌资产。
 * @param name 资产文件名（如 "codec_rgba8.png"）。
 * @return 匹配项指针；未找到返回 NULL。
 */
static const CodecAssetFixture* codec_asset_fixture_find(const char* name)
{
    size_t i;
    for (i = 0; i < sizeof(kCodecAssetFixtures) / sizeof(kCodecAssetFixtures[0]); ++i) {
        const CodecAssetFixture* f = &kCodecAssetFixtures[i];
        const char* a = f->name;
        const char* b = name;
        while (*a != '\0' && *b != '\0' && *a == *b) { ++a; ++b; }
        if (*a == '\0' && *b == '\0') return f;
    }
    return NULL;
}

